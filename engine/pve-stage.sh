#!/bin/sh
# Run on the PVE node which owns the VM. No SSH credentials are required.
# bash pve-stage.sh [plan|stage] VMID SRC_QCOW2 SRC_RAW TARGET_STORAGE QCOW2_SHA256 RAW_SHA256
set -eu
