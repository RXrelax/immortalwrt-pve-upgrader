import argparse
import contextlib
import hashlib
import json
import os
from pathlib import Path
import re
import socket
import stat
import struct
import subprocess
import sys
import tarfile
import tempfile


MIB = 1024 ** 2
GIB = 1024 * MIB
STATE_DIR = Path("/var/lib/router-upgrade-stage")
ROLES = ("system", "carrier")


class Stop(Exception):
    pass


def ensure(condition, message):
    if not condition:
        raise Stop(message)


def command(*argv):
    proc = subprocess.run(argv, stdin=subprocess.DEVNULL, capture_output=True, text=True,
                          env={**os.environ, "LC_ALL": "C"})
    ensure(proc.returncode == 0,
           f"{argv[0]} {argv[1]} failed ({proc.returncode}); see the local PVE task log.")
    return proc.stdout.strip()


def api(path, *args):
    return json.loads(command("pvesh", "get", path, *args, "--output-format", "json"))


def checked_layout(disk_gib, boot_mib):
    # This standalone node script follows the wizard's BIOS image profile.
    ensure(2 <= disk_gib <= 128 and 32 <= boot_mib <= 4096 and
           disk_gib * 1024 - boot_mib - 1 >= 512, "Unsupported system disk or partition size.")
    return disk_gib, boot_mib


def read_mbr(source):
    # Pin qemu-img to the same open file we hashed and checked for backing or
    # external data files. It needs only the first sector of the virtual disk.
    with tempfile.TemporaryDirectory(prefix="router-upgrade-mbr-") as tmp:
        target = Path(tmp) / "mbr"
        fd = source.fileno()
        proc = subprocess.run(["qemu-img", "dd", "-f", "qcow2", "-O", "raw",
                               "bs=512", "count=1", f"if=/proc/self/fd/{fd}", f"of={target}"],
                              stdin=subprocess.DEVNULL, capture_output=True, pass_fds=(fd,))
        ensure(proc.returncode == 0, "qemu-img could not read the QCOW2 partition table.")
        ensure(target.stat().st_size == 512, "Incomplete QCOW2 partition table.")
        return target.read_bytes()


def system_metadata(source, head):
    ensure(len(head) == 1024 and head[:4] == b"QFI\xfb" and
           struct.unpack_from(">I", head, 4)[0] == 3 and head[8:20] == bytes(12)
           and head[32:36] == bytes(4) and head[72:80] == bytes(8),
           "Expected a standalone, clean QCOW2 v3 from the wizard.")
    size = struct.unpack_from(">Q", head, 24)[0]
    ensure(size % GIB == 0 and 2 * GIB <= size <= 128 * GIB,
           "Unsupported QCOW2 virtual disk size.")
    mbr = read_mbr(source)
    ensure(len(mbr) == 512 and mbr[510:] == b"\x55\xaa" and any(mbr[:440])
           and not any(mbr[478:510]), "Expected a bootable MBR with two partitions.")
    boot = struct.unpack_from("<B3xB3xII", mbr, 446)
    root = struct.unpack_from("<B3xB3xII", mbr, 462)
    boot_mib, unaligned = divmod(boot[3], 2048)
    layout = checked_layout(size // GIB, boot_mib)
    root_mib = size // MIB - boot_mib - 1
    ensure(not unaligned and boot[:3] == (0x80, 0x83, 512) and
           root == (0, 0x83, boot[3] + 1024, root_mib * 2048),
           "Unexpected BIOS partition start, size, type or active flag.")
    return size, layout


def carrier_metadata(head, size):
    message = "Expected a MiB-aligned router recovery carrier generated by the wizard."
    ensure(len(head) == 1024 and head[257:262] == b"ustar"
           and size >= 4 * MIB and size % MIB == 0, message)
    try:
        member = tarfile.TarInfo.frombuf(head[:512], "ascii", "strict")
    except (tarfile.TarError, UnicodeError, ValueError):
        raise Stop(message) from None
    ensure(member.name == "RESTORE.ID" and member.type in (tarfile.REGTYPE, tarfile.AREGTYPE)
           and 0 < member.size <= 64, message)
    marker = head[512:512 + member.size]
    if marker == b"IMWRT-RESTORE-V2\n":
        return size, (15, 512)
    match = re.fullmatch(rb"IMWRT-RESTORE-V3 ([1-9][0-9]{0,2}) ([1-9][0-9]{0,3})\n", marker)
    ensure(match, message)
    return size, checked_layout(int(match[1]), int(match[2]))


def verified_source(role, volume, expected):
    path = Path(command("pvesm", "path", volume))
    ensure(path.is_absolute() and path.name == volume.split("/")[-1] and not path.is_symlink()
           and path.is_file(), f"{role}: missing or unexpected import file.")
    with path.open("rb") as f:
        initial = os.fstat(f.fileno())
        ensure(stat.S_ISREG(initial.st_mode), f"{role}: expected a regular import file.")
        head = f.read(1024)
        digest = hashlib.sha256(head)
        for chunk in iter(lambda: f.read(MIB), b""):
            digest.update(chunk)
        ensure(digest.hexdigest() == expected, f"{role}: SHA-256 mismatch or upload changed; inspect the import.")
        metadata = system_metadata(f, head) if role == "system" else carrier_metadata(head, initial.st_size)
        current = path.lstat()
        ensure((initial.st_dev, initial.st_ino, initial.st_size, initial.st_mtime_ns) ==
               (current.st_dev, current.st_ino, current.st_size, current.st_mtime_ns),
               f"{role}: upload changed; inspect the import.")
        return metadata


def inputs(vm, firmware, carrier, storage, fw_hash, raw_hash):
    ensure(re.fullmatch(r"[1-9][0-9]{2,8}", vm), "Use a numeric PVE VM ID (100 or greater).")
    ensure(re.fullmatch(r"[A-Za-z][A-Za-z0-9_.-]*", storage), "Invalid target storage ID.")
    sources = dict(zip(ROLES, (firmware, carrier)))
    hashes = dict(zip(ROLES, (fw_hash.lower(), raw_hash.lower())))
    sizes = {}
    layouts = {}
    for role, ext in zip(ROLES, ("qcow2", "raw")):
        vol = sources[role]
        ensure(re.fullmatch(r"[A-Za-z][A-Za-z0-9_.-]*:import/[A-Za-z0-9][A-Za-z0-9_.-]*\." + ext, vol),
               f"Expected a PVE import volume ID ending in .{ext}.")
        ensure(re.fullmatch(r"[a-f0-9]{64}", hashes[role]), f"Invalid {role} SHA-256.")
        sizes[role], layouts[role] = verified_source(role, vol, hashes[role])
    ensure(layouts["system"] == layouts["carrier"],
           "System and recovery carrier layouts differ. Select the matching image pair before import.")
    disk_gib, boot_mib = layouts["system"]
    print(f"Verified layout: disk {disk_gib} GiB, boot {boot_mib} MiB, root {disk_gib * 1024 - boot_mib - 1} MiB")
    return sources, hashes, sizes


def running_state(endpoint):
    status = api(endpoint + "/status/current")
    ensure(not status.get("ha", {}).get("managed"), "HA-managed VM: coordinate HA and use PVE's native workflow.")
    return status["status"]


def existing_hardware(cfg, rows):
    reserved = {"digest", *(row["slot"] for row in rows.values())}
    # Keep the protected VM configuration out of the persistent journal. A hash
    # detects modification of existing disks, NICs or boot order between imports.
    rest = {k: v for k, v in cfg.items() if k not in reserved}
    return hashlib.sha256(json.dumps(rest, sort_keys=True).encode()).hexdigest()


def config(endpoint):
    data = api(endpoint + "/config", "--current", "1")
    ensure(not data.get("lock") and not data.get("template"), "VM is locked or is a template.")
    ensure(data.get("bios", "seabios") == "seabios" and
           data.get("scsihw") in ("virtio-scsi-pci", "virtio-scsi-single"),
           "Expected a SeaBIOS VM with VirtIO SCSI. Review the VM Hardware in PVE.")
    ensure(re.fullmatch(r"[a-fA-F0-9]{40}", data.get("digest", "")), "PVE configuration digest unavailable.")
    pending = api(endpoint + "/pending")
    ensure(not any("pending" in row or row.get("delete") for row in pending),
           "VM has pending hardware/configuration changes. Review and settle them in PVE first.")
    return data


def plan_slots(cfg, tag):
    free = [f"scsi{i}" for i in range(31) if f"scsi{i}" not in cfg]
    ensure(len(free) >= 2, "Two free SCSI slots are required.")
    return {role: {"slot": slot, "serial": "ru" + role[0] + tag[:14], "phase": "new"}
            for role, slot in zip(ROLES, free[:2])}


def read_target(node, storage):
    status = api(f"/nodes/{node}/storage/{storage}/status")
    ensure(status.get("type") == "lvmthin" and status.get("enabled") and status.get("active")
           and "images" in status.get("content", "").split(","),
           "Target must be active PVE LVM-thin storage with Disk image content.")
    config = api("/storage/" + storage)
    vg, pool = config.get("vgname"), config.get("thinpool")
    ensure(config.get("type") == "lvmthin" and config.get("storage") == storage and
           all(isinstance(name, str) and name not in (".", "..") and
               re.fullmatch(r"[A-Za-z0-9+_.][A-Za-z0-9+_.-]{0,126}", name) for name in (vg, pool)),
           "Cannot identify the LVM-thin target VG and pool.")
    report = json.loads(command("vgs", "--reportformat", "json", "--units", "b", "--nosuffix",
                                "-o", "vg_extent_size,vg_name", vg))
    reports = report.get("report") if isinstance(report, dict) else None
    ensure(isinstance(reports, list) and len(reports) == 1 and isinstance(reports[0], dict),
           "Cannot determine the LVM extent size.")
    rows = reports[0].get("vg")
    ensure(isinstance(rows, list) and len(rows) == 1 and isinstance(rows[0], dict)
           and rows[0].get("vg_name") == vg, "Target VG is missing or ambiguous in the LVM extent report.")
    value = str(rows[0].get("vg_extent_size", "")).strip()
    units = re.fullmatch(r"([1-9][0-9]{0,18})(?:\.0+)?", value)
    ensure(units and int(units[1]) % 512 == 0, "Invalid LVM extent size in bytes.")
    return {"vg": vg, "pool": pool, "extent": int(units[1])}, int(status["avail"])


def attached_volume(cfg, row, storage, vm, role, expected_size):
    prop = cfg.get(row["slot"], "")
    fields = prop.split(",")
    options = dict(part.split("=", 1) for part in fields[1:] if "=" in part)
    if not prop:
        ensure(row["phase"] == "new",
               f"{role} import was attempted but the assigned slot is empty. Inspect the PVE task and Unused Disk entries; automatic retry stopped.")
        return None
    vol = fields[0].removeprefix("file=")
    ensure(row["phase"] != "new" and options.get("serial") == row["serial"] and
           re.fullmatch(re.escape(storage + ":vm-" + vm + "-disk-") + r"[0-9]+", vol)
           and options.get("ro", "0") == ("1" if role == "carrier" else "0")
           and options.get("backup", "1") == ("0" if role == "carrier" else "1")
           and row.get("volume", vol) == vol,
           f"{row['slot']} is occupied or changed; nothing will be overwritten.")
    size = re.fullmatch(r"([0-9]+)([KMGT]?)", options.get("size", ""))
    units = {"": 1, "K": 1024, "M": MIB, "G": 1024**3, "T": 1024**4}
    ensure(size and int(size[1]) * units[size[2]] == expected_size,
           f"{role}: the size recorded by PVE after import differs from the planned target volume.")
    return vol


def save(file, state):
    with tempfile.NamedTemporaryFile("w", dir=file.parent, delete=False) as tmp:
        filename = tmp.name
        try:
            json.dump(state, tmp)
            tmp.flush()
            os.fsync(tmp.fileno())
        except BaseException:
            os.unlink(filename)
            raise
    os.replace(filename, file)
    directory = os.open(file.parent, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(directory)
    finally:
        os.close(directory)


@contextlib.contextmanager
def stage_lock(directory, vm):
    import fcntl
    directory.mkdir(mode=0o700, exist_ok=True)
    metadata = directory.lstat()
    ensure(stat.S_ISDIR(metadata.st_mode) and metadata.st_uid == 0 and not metadata.st_mode & 0o077,
           "State directory must be root-owned and mode 0700.")
    fd = os.open(directory / (vm + ".lock"), os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW, 0o600)
    try:
        fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        yield
    finally:
        os.close(fd)


def run(mode, vm, sources, hashes, sizes, storage, state_dir=STATE_DIR, node=None):
    node = node or socket.gethostname().split(".")[0]
    ensure(re.fullmatch(r"[a-zA-Z0-9_.-]+", node), "Invalid local node name.")
    endpoint = "/nodes/" + node + "/qemu/" + vm
    identity = [vm, node, storage, hashes["system"], hashes["carrier"]]
    tag = hashlib.sha256(json.dumps(identity).encode()).hexdigest()
    file = state_dir / f"{vm}-{tag}.json"
    is_stage = mode == "stage"
    with stage_lock(state_dir, vm) if is_stage else contextlib.nullcontext():
        cfg = config(endpoint)
        status = running_state(endpoint)
        if is_stage:
            ensure(status == "stopped", "Shut down the VM first. No hotplug or automatic shutdown is performed.")
        guest_id = hashlib.sha256(cfg.get("smbios1", "").encode()).hexdigest()
        if file.exists():
            state = json.loads(file.read_text())
            ensure(state["identity"] == identity and state["guest"] == guest_id, "Saved job belongs to a different VM.")
            rows = state["rows"]
        else:
            for previous in state_dir.glob(f"{vm}-*.json"):
                phases = json.loads(previous.read_text())["rows"]
                ensure(all(phases[r]["phase"] == "done" for r in ROLES),
                       "A different import for this VM is unfinished. Inspect its PVE task, disk slots and Unused Disk entries; do not retry with different input files.")
            rows = plan_slots(cfg, tag)
            ensure(not any("serial=" + row["serial"] in str(value)
                           for row in rows.values() for value in cfg.values()),
                   "Existing job markers found without matching local state. Use the PVE Hardware view.")
            state = {"identity": identity, "guest": guest_id, "rows": rows,
                     "hardware": existing_hardware(cfg, rows)}
        # Older, already completed journals can be inspected. An incomplete
        # legacy journal has no independent copy of the original hardware hash.
        original = state.get("hardware")
        ensure(original or all(rows[r]["phase"] == "done" for r in ROLES),
               "Unfinished legacy import: review existing disks and boot order in PVE before continuing manually.")
        original = original or existing_hardware(cfg, rows)
        ensure(original == existing_hardware(cfg, rows),
               "VM configuration outside the two staging slots changed. Inspect Hardware and Boot Order in PVE.")
        backend, available = read_target(node, storage)
        ensure(state.setdefault("backend", backend) == backend,
               "Target VG, thin pool or extent size changed since the earlier import.")
        extent = backend["extent"]
        ensure(sizes["system"] % extent == 0,
               "The target VG extent would enlarge the verified system disk. Choose a compatible LVM-thin target.")
        # lvcreate -V rounds to VG extents. PVE's import-from volume-ID path
        # clones the source and reads the target LV size into the attached slot.
        allocated = {role: ((size + extent - 1) // extent) * extent for role, size in sizes.items()}
        print(f"Target LVM-thin extent: {extent} bytes")
        need = 0
        for role in ROLES:
            row = rows[role]
            ensure(row["phase"] != "inspect",
                   f"{role}: this import failed its post-copy checks. Inspect the staged volume and PVE task; automatic reuse is blocked.")
            ensure(re.fullmatch(r"scsi([0-9]|[12][0-9]|30)", row["slot"]) and
                   row["serial"] == "ru" + role[0] + tag[:14] and row["phase"] in ("new", "submitting", "done"),
                   "Invalid staging record.")
            vol = attached_volume(cfg, row, storage, vm, role, allocated[role])
            if not vol:
                need += allocated[role]
            print(f"{role}: {row['slot']} | source {sizes[role] // MIB} MiB | "
                  f"target {allocated[role]} bytes | {vol or 'to import'}")
        ensure(rows["system"]["slot"] != rows["carrier"]["slot"], "Conflicting staging slots.")
        ensure(available >= need, "Insufficient target storage for the planned disks.")
        if not is_stage:
            print(f"PLAN ONLY | VM {vm} is {status}. The source SHA-256 checks passed.")
            return
        for role in ROLES:
            row = rows[role]
            verified_source(role, sources[role], hashes[role])
            cfg = config(endpoint)
            ensure(running_state(endpoint) == "stopped", "VM state changed; stopped before further work.")
            ensure(existing_hardware(cfg, rows) == original, "VM hardware changed during import. Review the PVE task.")
            for name in ROLES:
                if rows[name]["phase"] == "done":
                    attached_volume(cfg, rows[name], storage, vm, name, allocated[name])
            vol = attached_volume(cfg, row, storage, vm, role, allocated[role])
            if not vol:
                current_backend, available = read_target(node, storage)
                ensure(current_backend == backend, "Target VG, thin pool or extent size changed during staging.")
                ensure(available >= allocated[role], "Insufficient target storage before import.")
                row["phase"] = "submitting"
                save(file, state)
                disk = (f"{storage}:0,import-from={sources[role]},serial={row['serial']},"
                        + ("ro=1,backup=0" if role == "carrier" else "ro=0,backup=1"))
                command("qm", "set", vm, "--digest", cfg["digest"], "--" + row["slot"], disk)
                cfg = config(endpoint)
                ensure(existing_hardware(cfg, rows) == original and running_state(endpoint) == "stopped",
                       "VM state or hardware changed during import. Review the staged disks in PVE.")
                vol = attached_volume(cfg, row, storage, vm, role, allocated[role])
                ensure(vol is not None, "PVE has not reported an attached volume. Inspect the task in PVE.")
                try:
                    verified_source(role, sources[role], hashes[role])
                    current_backend, _ = read_target(node, storage)
                    ensure(current_backend == backend, "Target VG, thin pool or extent size changed during staging.")
                except (OSError, Stop, ValueError, KeyError, TypeError):
                    # Restoring a changed upload or storage mapping later
                    # cannot validate the LV that qm just attached.
                    row.update(phase="inspect", volume=vol)
                    save(file, state)
                    raise
            row.update(phase="done", volume=vol)
            save(file, state)
            print(f"Attached: {role} {row['slot']} {vol}")
        print("STAGED. Check both disks in PVE Hardware, then follow the offline cutover guide. VM is not started by this script.")


def main():
    parser = argparse.ArgumentParser(description="Plan or stage two verified router disks on this local PVE node.")
    for arg in ("vmid", "firmware_import_volume", "recovery_import_volume", "target_storage", "firmware_sha256", "carrier_sha256"):
        parser.add_argument(arg)
    argv = sys.argv[1:]
    mode = argv.pop(0) if argv and argv[0] in ("plan", "stage") else "plan"
    args = parser.parse_args(argv)
    ensure(os.geteuid() == 0, "Run from the owning PVE node's root shell.")
    source, hashes, sizes = inputs(args.vmid, args.firmware_import_volume, args.recovery_import_volume,
                                    args.target_storage, args.firmware_sha256, args.carrier_sha256)
    run(mode, args.vmid, source, hashes, sizes, args.target_storage)


if __name__ == "__main__":
    try:
        main()
    except (Stop, OSError, ValueError, KeyError, TypeError) as exc:
        print("Stopped:", exc, file=sys.stderr)
        sys.exit(1)
